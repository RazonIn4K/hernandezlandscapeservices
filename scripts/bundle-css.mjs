#!/usr/bin/env node
// One render-blocking stylesheet instead of four or five (round 4; research 03
// R9, 05 X9). Concatenates, in their old load order, the Tailwind build plus the
// hand-written layers into assets/css/site.css. Edit the sources, never site.css:
//   npm run build   (Tailwind, then this bundle)
//   node scripts/bundle-css.mjs --check   (test:ci: fails if site.css is stale)
// Gallery and videos keep their own <link>s (they load gallery.css, not custom.css).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'assets/css/site.css';
const SOURCES = [
  'assets/css/styles.css',
  'assets/css/custom.css',
  'assets/css/video.css',
  'assets/css/rings.css',
];

const parts = SOURCES.map((rel) => {
  const css = fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\s+$/, '');
  return `/* ---- ${rel} ---- */\n${css}\n`;
});
const bundle = `/* @generated by scripts/bundle-css.mjs from ${SOURCES.length} sources; do not hand-edit. */\n${parts.join('')}`;
const outPath = path.join(ROOT, OUT);
const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;

if (process.argv.includes('--check')) {
  if (current !== bundle) {
    console.error(`bundle-css --check: ${OUT} is out of date. Run: npm run build`);
    process.exit(1);
  }
  console.log(`bundle-css --check: ${OUT} in sync (${Math.round(bundle.length / 1024)} KB).`);
} else {
  if (current !== bundle) fs.writeFileSync(outPath, bundle);
  console.log(`bundle-css: ${OUT} ${current === bundle ? 'unchanged' : 'written'} (${Math.round(bundle.length / 1024)} KB).`);
}
