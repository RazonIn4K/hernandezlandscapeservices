#!/usr/bin/env node
// Build the Spanish gallery from the English page and the shared dictionary.
// Photo cards are first generated into gallery/index.html by update-media.mjs.
// Keeping this page generated gives both languages the same photos, order,
// comparison control, and footer as the source gallery changes.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { renderSiteHeader, altFor, TWINS } from './site-header.mjs';
import { withIconSprite } from './icons.mjs';
import { applyBusinessNode } from './business-node.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'gallery', 'index.html');
const OUT = path.join(ROOT, 'es', 'gallery', 'index.html');
const CHECK = process.argv.includes('--check');
const fail = (message) => {
  console.error(`build-es-gallery: ${message}`);
  process.exit(1);
};

const i18n = fs.readFileSync(path.join(ROOT, 'assets', 'js', 'i18n.js'), 'utf8');
const dictionaryStart = i18n.indexOf('const translations = {');
const dictionaryEnd = i18n.indexOf('\n  };', dictionaryStart);
if (dictionaryStart < 0 || dictionaryEnd < 0) fail('translation dictionary not found');
const dictionary = vm.runInNewContext(`(${i18n.slice(dictionaryStart + 'const translations = '.length, dictionaryEnd + 4)})`);
const es = (key) => {
  const value = dictionary.es[key];
  if (typeof value !== 'string') fail(`missing Spanish translation for ${key}`);
  return value;
};

const head = `    <title>Fotos de jardinería y árboles | Hernandez</title>
    <meta name="description" content="Mira fotos de césped, jardineras, trabajo de árboles y equipo de Hernandez Landscape &amp; Tree Service LLC.">
    <meta name="robots" content="index, follow, max-image-preview:large">
    <meta property="og:title" content="Fotos de jardinería y árboles | Hernandez">
    <meta property="og:description" content="Fotos de césped, jardineras y trabajo de árboles del equipo de Hernandez Landscape.">
    <meta property="og:image" content="https://hernandezlandscapeservices.com/hernandez_images/google-profile-2026-branded-truck-trailers.jpg">
    <meta property="og:image:alt" content="Camioneta de Hernandez Landscape junto a dos remolques">
    <meta property="og:url" content="https://hernandezlandscapeservices.com/es/gallery/">
    <meta property="og:type" content="website">
    <meta property="og:site_name" content="Hernandez Landscape & Tree Service LLC">
    <meta property="og:locale" content="es_US">
    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="Fotos de jardinería y árboles | Hernandez">
    <meta name="twitter:description" content="Fotos de césped, jardineras y trabajo de árboles del equipo de Hernandez Landscape.">
    <meta name="twitter:image" content="https://hernandezlandscapeservices.com/hernandez_images/google-profile-2026-branded-truck-trailers.jpg">
    <meta name="twitter:image:alt" content="Camioneta de Hernandez Landscape junto a dos remolques">
    <link rel="canonical" href="https://hernandezlandscapeservices.com/es/gallery/">
    <link rel="alternate" hreflang="en" href="https://hernandezlandscapeservices.com/gallery/">
    <link rel="alternate" hreflang="es" href="https://hernandezlandscapeservices.com/es/gallery/">
    <link rel="alternate" hreflang="x-default" href="https://hernandezlandscapeservices.com/gallery/">

`;

let html = fs.readFileSync(SOURCE, 'utf8');
html = html.replace('<html lang="en">', '<!-- Generated by scripts/build-es-gallery.mjs from gallery/index.html. Do not edit by hand. -->\n<html lang="es">');
if (!html.includes('<html lang="es">')) fail('English gallery language tag not found');
const headStart = html.indexOf('    <title>');
const headEnd = html.indexOf('    <!-- Favicons -->', headStart);
if (headStart < 0 || headEnd < headStart) fail('gallery head anchors not found');
html = html.slice(0, headStart) + head + html.slice(headEnd);

// Rewrite source links before inserting the Spanish header. Links with no
// Spanish page stay on their English URL with a language annotation.
html = html.replace(/<a\b[^>]*>/gi, (tag) => {
  const match = tag.match(/\bhref="([^"]*)"/);
  if (!match) return tag;
  const href = match[1];
  if (!href.startsWith('/') || href.startsWith('//') || href.startsWith('/es/')) return tag;
  const [route, rest = ''] = href.split(/(?=[?#])/);
  const mapped = route === '/' ? `/es/${rest}` : TWINS.includes(route) ? `/es${route}${rest}` : href;
  let next = tag.replace(`href="${href}"`, `href="${mapped}"`);
  if (mapped === href && !/\bhreflang=/.test(next)) next = next.replace(/>$/, ' hreflang="en">');
  return next;
});

const headerStart = html.search(/^[ \t]*<header\b/m);
const headerEnd = html.indexOf('</header>', headerStart);
if (headerStart < 0 || headerEnd < 0) fail('gallery header not found');
html = html.slice(0, headerStart) + renderSiteHeader({
  lang: 'es',
  alt: altFor('/es/gallery/'),
  quoteHref: '/es/#quote',
  current: 'work',
}) + html.slice(headerEnd + '</header>'.length);

// Gallery keys sit on leaf elements, so the source markup remains intact and
// only their text changes. Attribute keys translate alt text and ARIA labels.
html = html.replace(/<([a-z][\w-]*)\b([^>]*\bdata-i18n-key="([^"]+)"[^>]*)>([\s\S]*?)<\/\1>/gi,
  (_, tag, attrs, key) => `<${tag}${attrs}>${es(key)}</${tag}>`);
html = html.replace(/<[^>]+>/g, (tag) => {
  let next = tag;
  for (const [keyAttr, target] of [['data-i18n-alt', 'alt'], ['data-i18n-aria-label', 'aria-label'], ['data-i18n-aria-valuetext', 'aria-valuetext']]) {
    const key = next.match(new RegExp(`\\b${keyAttr}="([^"]+)"`))?.[1];
    if (key) {
      const translated = target === 'aria-valuetext' ? es(key).replace('{{value}}', '50') : es(key);
      const value = translated.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
      next = next.replace(new RegExp(`\\b${target}="[^"]*"`), `${target}="${value}"`);
    }
  }
  return next;
});

// The gallery schema contains one business node shared across languages and
// five representative photos. Translate page and image descriptions here.
const media = JSON.parse(fs.readFileSync(path.join(ROOT, 'media', 'gallery.json'), 'utf8'));
const idBySrc = new Map(media.items.map((item) => [`https://hernandezlandscapeservices.com/${item.src}`, item.id]));
html = html.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/i, (_, open, body, close) => {
  const schema = JSON.parse(body);
  schema.name = 'Fotos de trabajos de Hernandez Landscape & Tree Service LLC';
  schema.url = 'https://hernandezlandscapeservices.com/es/gallery/';
  schema.inLanguage = 'es';
  for (const image of schema.associatedMedia ?? []) {
    const id = idBySrc.get(image.contentUrl);
    if (!id) fail(`gallery schema image not found in media/gallery.json: ${image.contentUrl}`);
    image.caption = es(`gallery.note.${id.replace(/-/g, '_')}`);
  }
  return `${open}\n${JSON.stringify(schema, null, 4)}\n    ${close}`;
});

html = withIconSprite(applyBusinessNode(html));
html = html.replace(/^[ \t]+$/gm, '');
const untranslatedLinks = [...html.matchAll(/<a\b[^>]*>/gi)]
  .map(([tag]) => tag)
  .filter((tag) => !tag.includes('class="lang-link"'))
  .filter((tag) => /href="\/(?:#quote|gallery\/|service-areas\/)/.test(tag));
if (untranslatedLinks.length) fail('untranslated gallery or quote link remains');
const previous = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (CHECK) {
  if (previous !== html) fail('es/gallery/index.html is out of date. Run: node scripts/build-es-gallery.mjs');
  console.log('build-es-gallery --check: es/gallery/index.html in sync.');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  if (previous !== html) fs.writeFileSync(OUT, html);
  console.log(`build-es-gallery: es/gallery/index.html ${previous === html ? 'unchanged' : 'written'}.`);
}
